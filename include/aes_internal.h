/**
 * @brief This function adds Round Keys to current Rtate using XOR operation
 * 
 * @param state current State of encryption/decryption
 * @param key pointer to 4 32-bit Round Keys
 */
static inline void aes_add_round_key(uint32_t *state, uint32_t *key) {
    for (size_t i = 0; i < 4; i++) {
        state[i] ^= key[i];
    }
}

/**
 * @brief This function applies SBox transformation to each byte in 32-bit operand for KeyExpansion
 * 
 * @param word operand for SBox transformation
 * @return 32-bit result with each byte transformed with SBox
 */
static inline uint32_t aes_sub_word(uint32_t dword) {
    return aes_sbox[(dword >> 24) & 0xFF] << 24 | aes_sbox[(dword >> 16) & 0xFF] << 16 | aes_sbox[(dword >> 8) & 0xFF] << 8 | aes_sbox[dword & 0xFF];
}

/**
 * @brief This function applies SBox transformation for each byte in current State in encryption cycles
 * 
 * @param state current State of encryption
 */
static inline void aes_sub_bytes(uint8_t *state) {
    for (size_t i = 0; i < 16; i++) {
        state[i] = aes_sbox[state[i]];
    }
}

/**
 * @brief This function applies SBox transformation for each byte in current State in decryption cycles
 * 
 * @param state current State of decryption
 */
static inline void aes_inv_sub_bytes(uint8_t *state) {
    for (size_t i = 0; i < 16; i++) {
        state[i] = aes_inverse_sbox[state[i]];
    }
}

/**
 * @brief This function multiplies one byte (which could be represented as polynomial) in galois finite field GF(2^8) modulo 0x11B polynomial (x^8 + x^4 + x^3 + x + 1) by 0x02 (or just x)
 * 
 * @param byte operand-polynomial
 * @return polynomial, represented as byte - result of multiplication by x
 */
static inline uint8_t aes_xtime(uint8_t byte) {

    if (byte >> 7 & 0x1) {
        return ((uint8_t)(byte << 1)) ^ 0x1b;
    } else {
        return (uint8_t)(byte << 1);
    }
}

/**
 * @brief This function multiplies two polynomials (represented as two bytes) in galois finite field GC(2^8) modulo x^8 + x^4 + x^3 + x + 1 (or 0x11B)
 * 
 * @param byte1 first polynomial-operand
 * @param byte2 second polynomial-operand
 * @return polynomial, represented as byte - result of multiplication of two polynomials
 */
static inline uint8_t aes_galois_mult(uint8_t byte1, uint8_t byte2) {

    uint8_t curr_mult = byte1;
    uint8_t result = 0;

    while (byte2 != 0) {
        if (byte2 & 1) {
            result ^= curr_mult;
        }
        curr_mult = aes_xtime(curr_mult);
        byte2 >>= 1;
    }
    return result;
}


/**
 * @brief This function treats each column in state as four-term polynomial and multiplies it by 0x03x^3 + 0x01x^2 + 0x01x + 0x02 modulo x^4 + 1
 * 
 * @param state current State of encryption
 */
static inline void aes_mix_columns(uint8_t *state) {
    
    uint32_t *word_state = (uint32_t *)state;

    for (size_t i = 0; i < 4; i++) {
        uint8_t s0 = word_state[i] & 0xFF;
        uint8_t s1 = (word_state[i] >> 8) & 0xFF;
        uint8_t s2 = (word_state[i] >> 16) & 0xFF;
        uint8_t s3 = (word_state[i] >> 24) & 0xFF;

        uint8_t s0_new = aes_galois_mult(0x02, s0) ^ aes_galois_mult(0x03, s1) ^ s2 ^ s3;
        uint8_t s1_new = s0 ^ aes_galois_mult(0x02, s1) ^ aes_galois_mult(0x03, s2) ^ s3;
        uint8_t s2_new = s0 ^ s1 ^ aes_galois_mult(0x02, s2) ^ aes_galois_mult(0x03, s3);
        uint8_t s3_new = aes_galois_mult(0x03, s0) ^ s1 ^ s2 ^ aes_galois_mult(0x02, s3);

        word_state[i] = (s3_new << 24) | (s2_new << 16) | (s1_new << 8) | s0_new;
    }

}

/**
 * @brief This function treats each column in state as four-term polynomial and multiplies it by 0x0bx^3 + 0x0dx^2 + 0x09x + 0x0e (inverse polynomial to one in MixColumns) modulo x^4 + 1
 * 
 * @param state current State of decryption
 */
static inline void aes_inv_mix_columns(uint8_t *state) {
    
    uint32_t *word_state = (uint32_t *)state;

    for (size_t i = 0; i < 4; i++) {
        uint8_t s0 = word_state[i] & 0xFF;
        uint8_t s1 = (word_state[i] >> 8) & 0xFF;
        uint8_t s2 = (word_state[i] >> 16) & 0xFF;
        uint8_t s3 = (word_state[i] >> 24) & 0xFF;

        uint8_t s0_new = aes_galois_mult(0x0e, s0) ^ aes_galois_mult(0x0b, s1) ^ aes_galois_mult(0x0d, s2) ^ aes_galois_mult(0x09, s3);
        uint8_t s1_new = aes_galois_mult(0x09, s0) ^ aes_galois_mult(0x0e, s1) ^ aes_galois_mult(0x0b, s2) ^ aes_galois_mult(0x0d, s3);
        uint8_t s2_new = aes_galois_mult(0x0d, s0) ^ aes_galois_mult(0x09, s1) ^ aes_galois_mult(0x0e, s2) ^ aes_galois_mult(0x0b, s3);
        uint8_t s3_new = aes_galois_mult(0x0b, s0) ^ aes_galois_mult(0x0d, s1) ^ aes_galois_mult(0x09, s2) ^ aes_galois_mult(0x0e, s3);

        word_state[i] = (s3_new << 24) | (s2_new << 16) | (s1_new << 8) | s0_new;
    }

}

/**
 * @brief This function performs cyclic left rotation on rows in State, rotation distance is calculated by number of row
 * 
 * @param state Current State for encryption
 */
static void aes_shift_rows(uint8_t *state) {

    for (size_t i = 1; i < 4; i++) {
        uint32_t mix_operand = 0;
        for (size_t j = 0; j < 16; j += 4) {
            mix_operand <<= 8;
            mix_operand |= state[i+j];
        }

        mix_operand = __rold(mix_operand, i << 3);

        for (int j = 12; j >= 0; j -= 4) {
            state[i+j] = mix_operand & 0xFF;
            mix_operand >>= 8;
        }
    }

}

/**
 * @brief This function performs cyclic right rotation on rows in State, rotation distance is calculated by number of row
 * 
 * @param state Current State for decryption
 */
static void aes_inv_shift_rows(uint8_t *state) {

    for (size_t i = 1; i < 4; i++) {
        uint32_t mix_operand = 0;
        for (size_t j = 0; j < 16; j += 4) {
            mix_operand <<= 8;
            mix_operand |= state[i+j];
        }

        mix_operand = __rord(mix_operand, i << 3);

        for (int j = 12; j >= 0; j -= 4) {
            state[i+j] = mix_operand & 0xFF;
            mix_operand >>= 8;
        }
    }

}

